"""Build, sign locally, validate, and zip the Apple Silicon application."""
import json
import io
from pathlib import Path
import platform
import plistlib
import subprocess
import sys
import unittest
from mac_target import require_native_mac
from platform_support import VERSION

ROOT=Path(__file__).resolve().parent

def spec_text(root=ROOT):
    return f"""# Generated by build_mac.py; rerun the builder after moving the source folder.
from pathlib import Path
from PyInstaller.utils.hooks import collect_all
root=Path({str(root)!r})
datas=[(str(root/'.models'),'.models'),(str(root/'offline_worker.py'),'.'),(str(root/'Lisanslar'),'Lisanslar')]
binaries=[]
hiddenimports=['speech_worker','captions','export_pipeline','jump_cut','timeline_markers','unittest.mock']
for package in ('faster_whisper','ctranslate2','onnxruntime','av','tokenizers','psutil','imageio_ffmpeg'):
    package_datas,package_binaries,package_imports=collect_all(package)
    datas+=package_datas;binaries+=package_binaries;hiddenimports+=package_imports
excluded=['ctranslate2.converters','ctranslate2.specs','onnxruntime.transformers','onnxruntime.tools','onnxruntime.quantization']
a=Analysis([str(root/'entrypoint.py')],pathex=[str(root)],binaries=binaries,datas=datas,
           hiddenimports=hiddenimports,excludes=excluded,noarchive=False,optimize=0)
pyz=PYZ(a.pure)
exe=EXE(pyz,a.scripts,[],exclude_binaries=True,name='SesPusula',debug=False,
        bootloader_ignore_signals=False,strip=False,upx=False,console=False,
        target_arch='arm64',codesign_identity=None,entitlements_file=None)
collection=COLLECT(exe,a.binaries,a.datas,strip=False,upx=False,name='SesPusula')
app=BUNDLE(collection,name='SesPusula.app',bundle_identifier='com.sespusula.silencecutter.mac',
           version={VERSION!r},info_plist={{
               'CFBundleShortVersionString':{VERSION!r},'CFBundleVersion':{VERSION!r},
               'CFBundleDisplayName':'SesPusula','LSMinimumSystemVersion':'26.0',
               'NSHighResolutionCapable':True,'NSRequiresAquaSystemAppearance':False,
               'NSSupportsAutomaticGraphicsSwitching':True}})
"""

def run_tests(root=ROOT):
    stream=io.StringIO()
    suite=unittest.defaultTestLoader.discover(str(root/'tests'))
    result=unittest.TextTestRunner(stream=stream,verbosity=2).run(suite)
    details=stream.getvalue()
    print(details,flush=True)
    if not result.wasSuccessful():
        report=root/'KURULUM-HATASI.txt'
        report.write_text('SesPusula - uygulama olusturulamadi\n\n'
            +'Asil test hatasi asagidadir. Bu dosyanin icerigini paylasabilirsiniz.\n\n'
            +details,encoding='utf-8')
        if sys.platform=='darwin':
            try:subprocess.run(['/usr/bin/open','-a','TextEdit',str(report)],check=False)
            except OSError:pass
        raise SystemExit(f'Test basarisiz. Ayrinti: {report}')


def main():
    try:require_native_mac()
    except RuntimeError as exc:raise SystemExit(str(exc))
    run_tests()
    output=ROOT/'Dagitim/arm64';output.mkdir(parents=True,exist_ok=True)
    work=ROOT/'.build/arm64';work.mkdir(parents=True,exist_ok=True)
    spec=work/'SesPusula.spec';spec.write_text(spec_text(),encoding='utf-8')
    subprocess.run([sys.executable,'-m','PyInstaller','--noconfirm','--clean',
        '--distpath',str(output),'--workpath',str(work/'work'),str(spec)],cwd=ROOT,check=True)
    app=output/'SesPusula.app';executable=app/'Contents/MacOS/SesPusula'
    info=plistlib.loads((app/'Contents/Info.plist').read_bytes())
    if info.get('LSMinimumSystemVersion')!='26.0' or info.get('CFBundleVersion')!=VERSION:
        raise SystemExit('Uygulama surumu veya macOS hedefi uyusmuyor.')
    arch=subprocess.check_output(['/usr/bin/lipo','-archs',str(executable)],text=True).strip()
    if arch!='arm64':raise SystemExit(f'Beklenmeyen binary mimarisi: {arch}')
    subprocess.run(['/usr/bin/codesign','--verify','--deep','--strict',str(app)],check=True)
    report=output/'mac-native-self-test.json'
    subprocess.run([str(executable),'--self-test','--require-contained-runtime','--report',str(report)],check=True)
    if not json.loads(report.read_text(encoding='utf-8'))['passed']:raise SystemExit('Yerel Mac testi basarisiz.')
    archive=output/f'SesPusula-{VERSION}-macOS26-arm64.zip'
    subprocess.run(['/usr/bin/ditto','-c','-k','--sequesterRsrc','--keepParent',str(app),str(archive)],check=True)
    status={'version':VERSION,'architecture':arch,'build_macos':platform.mac_ver()[0],
            'native_macos_tested':True,'native_selftest_passed':True,'codesign_verified':True,
            'signing':'local ad-hoc; not Developer ID/notarized','capcut_render_verified':False,
            'device_matrix_verified':False,'app':str(app),'archive':str(archive)}
    (output/'build-report.json').write_text(json.dumps(status,indent=2,ensure_ascii=False),encoding='utf-8')
    print(f'Hazir: {app}\nDagitim ZIP: {archive}\n.app dosyasini Applications klasorune kopyalayabilirsiniz.')
    subprocess.run(['/usr/bin/open','-R',str(app)],check=False)

if __name__=='__main__':main()
